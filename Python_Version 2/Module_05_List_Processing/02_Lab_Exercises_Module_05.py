# Exercise 5 (05-02): ชื่อจริง - ชื่อเล่น (จากภาพที่ 4)
# ------------------------------------------------------------------------------
# Input: บรรทัดแรกเป็น N และตามด้วยชื่อ N บรรทัด
# Process: สลับชื่อจริงเป็นชื่อเล่น หรือชื่อเล่นเป็นชื่อจริง (ไม่ใช้ if...elif...)
# Output: N บรรทัด แสดงชื่อคู่ตรงข้าม (ถ้าไม่เจอแสดง Not found)
reals = ["Robert", "William", "James", "John", "Margaret", "Edward", "Sarah", "Andrew", "Anthony", "Deborah"]
nicks = ["Dick", "Bill", "Jim", "Jack", "Peggy", "Ed", "Sally", "Andy", "Tony", "Debbie"]

n = int(input())
for _ in range(n):
    name = input().strip()
    if name in reals:
        idx = reals.index(name)
        print(nicks[idx])
    elif name in nicks:
        idx = nicks.index(name)
        print(reals[idx])
    else:
        print("Not found")


