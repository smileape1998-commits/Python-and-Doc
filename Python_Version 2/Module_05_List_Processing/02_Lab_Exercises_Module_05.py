# Exercise 1: Dot Product ของเวกเตอร์ (จากภาพที่ 1)
# ------------------------------------------------------------------------------
# Input: มี 2 บรรทัด แต่ละบรรทัดเก็บสมาชิกของเวกเตอร์ ซึ่งเป็นจำนวนจริงหลายจำนวนคั่นด้วยช่องว่าง
# Process: คำนวณ dot product ของเวกเตอร์ v1 กับ v2
# Output: แสดงคำว่า Error ถ้า v1 และ v2 มีขนาดไม่เท่ากัน แต่ถ้าเท่ากัน แสดงค่า dot product ที่คำนวณได้
v1 = [float(x) for x in input().split()]
v2 = [float(x) for x in input().split()]

if len(v1) != len(v2):
    print("Error")
else:
    dot_product = sum(v1[i] * v2[i] for i in range(len(v1)))
    print(dot_product)


