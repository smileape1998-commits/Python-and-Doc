# Exercise 3: ฐานนิยมในแฟ้มข้อมูล (Mode in File) (จากภาพที่ 2)
# ------------------------------------------------------------------------------
# Input: หนึ่งบรรทัดเป็นชื่อแฟ้ม แฟ้มนี้เก็บจำนวนเต็มบรรทัดละจำนวน
# Process: หาว่าจำนวนเต็มใดในแฟ้มปรากฏซ้ำกันมากที่สุด ถ้ามีซ้ำกันมากที่สุดหลายตัว ให้หาทุกตัว
# Output: ข้อมูลทุกตัวที่ปรากฏซ้ำกันมากที่สุดในแฟ้ม เรียงตามลำดับที่ปรากฏในแฟ้ม
filename = input().strip()

counts = {}
order = []

with open(filename, "r") as f:
    for line in f:
        line = line.strip()
        if line:
            num = int(line)
            if num not in counts:
                counts[num] = 0
                order.append(num)
            counts[num] += 1

if counts:
    max_freq = max(counts.values())
    for num in order:
        if counts[num] == max_freq:
            print(num)


