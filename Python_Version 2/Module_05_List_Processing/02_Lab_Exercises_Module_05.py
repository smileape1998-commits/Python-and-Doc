# Exercise 4 (05-01): เลขไหนหายไป (จากภาพที่ 3)
# ------------------------------------------------------------------------------
# Input: สตริงหนึ่งบรรทัด
# Process: หาตัวเลข 0 ถึง 9 ที่ไม่ปรากฏในสตริง
# Output: รายการเลข 0-9 ที่ไม่ปรากฏ เรียงจากน้อยไปมากคั่นด้วยจุลภาค (ถ้ามีครบแสดง None)
text = input()

missing = []
for digit in "0123456789":
    if digit not in text:
        missing.append(digit)

if missing:
    print(",".join(missing))
else:
    print("None")


