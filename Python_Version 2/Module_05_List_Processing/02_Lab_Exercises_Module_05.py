# Exercise 6 (05-04): การนับจำนวนยอด (จากภาพที่ 5)
# ------------------------------------------------------------------------------
# Input: รายการของจำนวนจริงบนบรรทัดเดียวกันคั่นด้วยช่องว่าง
# Process: นับจุดยอด (ค่าที่มากกว่าตัวซ้ายและตัวขวา)
# Output: จำนวนยอด
data = [float(x) for x in input().split()]

peaks = 0
for i in range(1, len(data) - 1):
    if data[i] > data[i - 1] and data[i] > data[i + 1]:
        peaks += 1

print(peaks)
