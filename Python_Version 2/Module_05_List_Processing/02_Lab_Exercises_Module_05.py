# Exercise 2: การเรียงลำดับจำนวนเต็ม (จากภาพที่ 1)
# ------------------------------------------------------------------------------
# Input: บรรทัดแรกเป็นจำนวนเต็ม n และมีอีก n บรรทัด แต่ละบรรทัดเป็นจำนวนเต็ม 1 จำนวน
# Process: เรียงลำดับจำนวนเต็มทั้ง n ตัวจากน้อยไปมาก
# Output: จำนวนเต็มทั้ง n ที่เรียงจากน้อยไปมากบนบรรทัดเดียวกันคั่นด้วยจุลภาค ,
n = int(input())
data = []
for _ in range(n):
    data.append(int(input()))

data.sort()
print(",".join(str(x) for x in data))


